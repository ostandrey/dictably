def minutes_docx(ctx: ExportCtx) -> bytes:
    L = ctx.labels
    doc = Document()
    _docx_set_style(doc)
    title = _doc_title(ctx.media, ctx.minutes)
    h = doc.add_heading(title, level=1)
    for run in h.runs:
        _set_run_font(run, bold=True)

    official = _is_official(ctx.minutes)
    meta = doc.add_paragraph()
    if official:
        run = meta.add_run(
            f"{_fmt_meeting_date(ctx.media, ctx.locale)} · {_fmt_duration(ctx.media.duration_ms)}\n"
        )
        _set_run_font(run)
        attendees = _attendee_names(ctx.speakers, ctx.minutes)
        if attendees:
            run = meta.add_run(f"{L['attendees']}: {', '.join(attendees)}\n")
            _set_run_font(run)
    else:
        for line in (
            f"{L['file']}: {ctx.media.filename}",
            f"{L['date']}: {_fmt_meeting_date(ctx.media, ctx.locale)}",
            f"{L['duration']}: {_fmt_duration(ctx.media.duration_ms)}",
        ):
            run = meta.add_run(line + "\n")
            _set_run_font(run)
        our, their, other = _party_buckets(ctx.speakers)
        if our:
            run = meta.add_run(f"{L['our_side']}: {', '.join(our)}\n")
            _set_run_font(run)
        if their:
            run = meta.add_run(f"{L['their_side']}: {', '.join(their)}\n")
            _set_run_font(run)
        if other:
            run = meta.add_run(f"{L['participants']}: {', '.join(other)}\n")
            _set_run_font(run)

    def add_items(heading: str | None, entries: list[tuple[str, Any]]) -> None:
        if not entries:
            return
        if heading:
            sh = doc.add_heading(heading, level=2)
            for run in sh.runs:
                _set_run_font(run, bold=True)
        for kind, item in entries:
            text = getattr(item, "text", "") or ""
            start_ms = getattr(item, "start_ms", None)
            tc = _fmt_clock(start_ms)
            url = _tc_url(ctx, start_ms)
            meta_bits = _item_meta(ctx.speakers, item)
            para = doc.add_paragraph()
            if kind == "task":
                pr = para.add_run("☐ ")
                _set_run_font(pr)
            if tc and url:
                _add_hyperlink(para, url, f"[{tc}]")
                sp = para.add_run(" ")
                _set_run_font(sp)
            elif tc:
                tr = para.add_run(f"[{tc}] ")
                _set_run_font(tr)
                tr.font.color.rgb = RGBColor(0x6B, 0x7C, 0x76)
            body = para.add_run(text)
            _set_run_font(body)
            if meta_bits:
                meta_para = doc.add_paragraph()
                mrun = meta_para.add_run(meta_bits)
                _set_run_font(mrun)
                mrun.font.color.rgb = RGBColor(0x6B, 0x7C, 0x76)
                mrun.font.size = Pt(9)
                meta_para.paragraph_format.space_after = Pt(4)
                meta_para.paragraph_format.left_indent = Pt(18)
            else:
                para.paragraph_format.space_after = Pt(4)

    def add_label(label: str) -> None:
        p = doc.add_paragraph()
        r = p.add_run(label)
        _set_run_font(r, bold=True)
        r.font.size = Pt(10)
        r.font.color.rgb = RGBColor(0x4A, 0x5C, 0x56)

    if official:
        agenda = list(getattr(ctx.minutes, "agenda", None) or [])
        if agenda:
            sh = doc.add_heading(L["agenda"], level=2)
            for run in sh.runs:
                _set_run_font(run, bold=True)
            for i, item in enumerate(agenda, start=1):
                para = doc.add_paragraph(f"{i}. {getattr(item, 'text', '') or ''}")
                for run in para.runs:
                    _set_run_font(run)
        for n, bucket in enumerate(group_by_agenda(ctx.minutes), start=1):
            if bucket.agenda is not None:
                heading = f"{n}. {getattr(bucket.agenda, 'text', '') or ''}"
            else:
                heading = L["other"]
            sh = doc.add_heading(heading, level=2)
            for run in sh.runs:
                _set_run_font(run, bold=True)
            if bucket.heard:
                add_label(L["heard_official"])
                add_items(None, [("plain", x) for x in bucket.heard])
            if bucket.decisions:
                add_label(L["decisions_official"])
                add_items(None, [("plain", x) for x in bucket.decisions])
            if bucket.tasks:
                add_label(L["tasks_official"])
                add_items(None, [("task", x) for x in bucket.tasks])
        add_items(L["open_questions"], [("plain", x) for x in ctx.minutes.open_questions])
        sign = doc.add_paragraph()
        sr = sign.add_run(f"{L['prepared_by']}: __________    {L['approved_by']}: __________")
        _set_run_font(sr)
        sr.font.color.rgb = RGBColor(0x4A, 0x5C, 0x56)
    else:
        if ctx.minutes.summary:
            sh = doc.add_heading(L["summary"], level=2)
            for run in sh.runs:
                _set_run_font(run, bold=True)
            for p in ctx.minutes.summary:
                para = doc.add_paragraph(p.text)
                for run in para.runs:
                    _set_run_font(run)
        for _pid, label, items in _party_groups(ctx.minutes):
            add_items(L["agreed_to"].replace("{label}", label), items)
        add_items(L["decisions"], [("plain", x) for x in ctx.minutes.decisions])
        add_items(L["deadlines"], [("plain", x) for x in ctx.minutes.deadlines_and_facts])
        add_items(L["open_questions"], [("plain", x) for x in ctx.minutes.open_questions])

    foot = doc.add_paragraph()
    fr = foot.add_run(L["footer"])
    _set_run_font(fr)
    fr.italic = True
    fr.font.color.rgb = RGBColor(0x6B, 0x7C, 0x76)
    fr.font.size = Pt(9)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


