def _ui_locale(raw: str | None) -> str:
    code = (raw or "en").lower().replace("_", "-")
    if code.startswith("uk"):
        return "uk"
    return "en"


def _labels_for(locale: str) -> dict[str, str]:
    return _LABELS[_ui_locale(locale)]


def _safe_stem(name: str) -> str:
    stem = Path(name).stem or "recording"
    cleaned = re.sub(r"[^\w\-]+", "_", stem, flags=re.UNICODE).strip("_")
    return (cleaned or "recording")[:80]


def _fmt_clock(ms: int | None) -> str:
    if ms is None:
        return ""
    total = max(0, int(ms) // 1000)
    h, rem = divmod(total, 3600)
    m, s = divmod(rem, 60)
    if h:
        return f"{h}:{m:02d}:{s:02d}"
    return f"{m}:{s:02d}"


def _fmt_srt_ts(ms: int) -> str:
    total = max(0, int(ms))
    h, rem = divmod(total // 1000, 3600)
    m, rem2 = divmod(rem, 60)
    s = rem2
    millis = total % 1000
    return f"{h:02d}:{m:02d}:{s:02d},{millis:03d}"


def _fmt_vtt_ts(ms: int) -> str:
    return _fmt_srt_ts(ms).replace(",", ".")


def _fmt_duration(ms: int | None) -> str:
    if not ms:
        return "—"
    return _fmt_clock(ms)


def _fmt_date(dt: datetime | None, locale: str) -> str:
    if dt is None:
        return "—"
    local = dt
    if locale == "uk":
        return f"{local.day} {_UK_MONTHS[local.month - 1]} {local.year}, {local.hour:02d}:{local.minute:02d}"
    return local.strftime("%d %b %Y, %H:%M")


def _speaker_label(speakers: list[Speaker], label: str | None) -> str:
    if not label:
        return "Speaker"
    for sp in speakers:
        if sp.label == label:
            return (sp.display_name or "").strip() or sp.label
    return label


def _party_buckets(speakers: list[Speaker]) -> tuple[list[str], list[str], list[str]]:
    our: list[str] = []
    their: list[str] = []
    other: list[str] = []
    for sp in speakers:
        name = (sp.display_name or "").strip() or sp.label
        if sp.party == "our":
            our.append(name)
        elif sp.party == "their":
            their.append(name)
        else:
            other.append(name)
    return our, their, other


def _minutes_model(result: dict[str, Any], segments: list[dict[str, Any]]) -> Minutes:
    enriched = enrich_start_ms(dict(result or {}), segments)
    return Minutes.model_validate(enriched)


def _recording_path(locale: str, media_id: UUID) -> str:
    prefix = "/uk" if locale == "uk" else ""
    return f"{prefix}/app/r/?id={media_id}"


def _tc_url(ctx: ExportCtx, start_ms: int | None) -> str | None:
    if start_ms is None:
        return None
    sec = max(0, int(start_ms) // 1000)
    base = ctx.base_url.rstrip("/")
    return f"{base}{ctx.recording_path}&t={sec}"


def _item_meta(speakers: list[Speaker], item: Any) -> str:
    bits: list[str] = []
    owner = getattr(item, "owner_speaker", None)
    if owner:
        bits.append(_speaker_label(speakers, owner))
    due = getattr(item, "due_text", None)
    if due:
        bits.append(str(due))
    return " · ".join(bits)


def _party_groups(minutes: Minutes) -> list[tuple[str, str, list[tuple[str, Any]]]]:
    """Mirror MinutesPanel: agreements + tasks grouped by party (kind, item)."""
    by_party: dict[str, list[tuple[str, Any]]] = {}
    for a in minutes.agreements:
        by_party.setdefault(a.party_id or "_", []).append(("agreement", a))
    for t in minutes.tasks:
        by_party.setdefault(t.party_id or "_", []).append(("task", t))
    ordered = [p.id for p in minutes.parties]
    for pid in list(by_party):
        if pid not in ordered:
            ordered.append(pid)
    out: list[tuple[str, str, list[tuple[str, Any]]]] = []
    party_label = {p.id: p.label for p in minutes.parties}
    for pid in ordered:
        items = by_party.get(pid) or []
        if not items:
            continue
        label = (party_label.get(pid) or pid).strip() or pid
        out.append((pid, label, items))
    return out


def _doc_title(media: Media, minutes: Minutes) -> str:
    return minutes.title or Path(media.filename).stem or "Minutes"


def minutes_markdown(ctx: ExportCtx) -> str:
    L = ctx.labels
    title = _doc_title(ctx.media, ctx.minutes)
    lines: list[str] = [
        f"# {title}",
        "",
        f"- **{L['file']}:** {ctx.media.filename}",
        f"- **{L['date']}:** {_fmt_date(ctx.media.created_at, ctx.locale)}",
        f"- **{L['duration']}:** {_fmt_duration(ctx.media.duration_ms)}",
    ]
    our, their, other = _party_buckets(ctx.speakers)
    if our:
        lines.append(f"- **{L['our_side']}:** {', '.join(our)}")
    if their:
        lines.append(f"- **{L['their_side']}:** {', '.join(their)}")
    if other:
        lines.append(f"- **{L['participants']}:** {', '.join(other)}")
    lines.append("")

    if ctx.minutes.summary:
        lines.append(f"## {L['summary']}")
        lines.append("")
        for p in ctx.minutes.summary:
            lines.append(p.text)
            lines.append("")

    for _pid, label, items in _party_groups(ctx.minutes):
        heading = L["agreed_to"].replace("{label}", label)
        lines.append(f"## {heading}")
        lines.append("")
        for kind, item in items:
            text = getattr(item, "text", "") or ""
            start_ms = getattr(item, "start_ms", None)
            tc = _fmt_clock(start_ms)
            url = _tc_url(ctx, start_ms)
            mark = "☐ " if kind == "task" else ""
            if tc and url:
                prefix = f"{mark}[`{tc}`]({url}) "
            elif tc:
                prefix = f"{mark}`{tc}` "
            else:
                prefix = mark
            meta = _item_meta(ctx.speakers, item)
            if meta:
                lines.append(f"- {prefix}{text}")
                lines.append(f"  - {meta}")
            else:
                lines.append(f"- {prefix}{text}")
        lines.append("")

    def plain_section(heading: str, items: list[Any]) -> None:
        if not items:
            return
        lines.append(f"## {heading}")
        lines.append("")
        for item in items:
            text = getattr(item, "text", "") or ""
            start_ms = getattr(item, "start_ms", None)
            tc = _fmt_clock(start_ms)
            url = _tc_url(ctx, start_ms)
            if tc and url:
                prefix = f"[`{tc}`]({url}) "
            elif tc:
                prefix = f"`{tc}` "
            else:
                prefix = ""
            lines.append(f"- {prefix}{text}")
        lines.append("")

    plain_section(L["decisions"], list(ctx.minutes.decisions))
    plain_section(L["deadlines"], list(ctx.minutes.deadlines_and_facts))
    plain_section(L["open_questions"], list(ctx.minutes.open_questions))
    lines.append(f"_{L['footer']}_")
    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


