def _set_run_font(run: Any, *, bold: bool = False) -> None:
    run.font.name = "Onest"
    run.font.size = Pt(11)
    if bold:
        run.bold = True
    r = run._element.get_or_add_rPr()
    rfonts = r.get_or_add_rFonts()
    rfonts.set(qn("w:ascii"), "Onest")
    rfonts.set(qn("w:hAnsi"), "Onest")
    rfonts.set(qn("w:cs"), "Onest")
    rfonts.set(qn("w:eastAsia"), "Onest")


def _add_hyperlink(paragraph: Any, url: str, text: str) -> None:
    """Add an external hyperlink run (python-docx has no first-class helper)."""
    from docx.oxml import OxmlElement

    part = paragraph.part
    r_id = part.relate_to(
        url,
        "http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink",
        is_external=True,
    )
    hyperlink = OxmlElement("w:hyperlink")
    hyperlink.set(qn("r:id"), r_id)
    new_run = OxmlElement("w:r")
    rPr = OxmlElement("w:rPr")
    color = OxmlElement("w:color")
    color.set(qn("w:val"), "0F766E")
    u = OxmlElement("w:u")
    u.set(qn("w:val"), "single")
    rFonts = OxmlElement("w:rFonts")
    rFonts.set(qn("w:ascii"), "Onest")
    rFonts.set(qn("w:hAnsi"), "Onest")
    sz = OxmlElement("w:sz")
    sz.set(qn("w:val"), "22")
    rPr.append(rFonts)
    rPr.append(color)
    rPr.append(u)
    rPr.append(sz)
    new_run.append(rPr)
    t = OxmlElement("w:t")
    t.text = text
    new_run.append(t)
    hyperlink.append(new_run)
    paragraph._p.append(hyperlink)


def _docx_set_style(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "Onest"
    style.font.size = Pt(11)
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
